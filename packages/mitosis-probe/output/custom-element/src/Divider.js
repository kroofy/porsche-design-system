/**
 * Usage:
 *
 *  <probe-divider></probe-divider>
 *
 */
class ProbeDivider extends HTMLElement {
  get _root() {
    return this.shadowRoot || this;
  }

  constructor() {
    super();
    const self = this;

    this.state = {
      get background() {
        // Mirrors colorMap in divider-styles.ts: PDS token var with light-theme fallback.
        const map = {
          "contrast-lower":
            "var(--p-color-contrast-lower, hsl(234 6% 32.9% / 0.324))",
          "contrast-low":
            "var(--p-color-contrast-low, hsl(240 5.3% 14.9% / 0.5))",
          "contrast-medium":
            "var(--p-color-contrast-medium, hsl(240 6.1% 7% / 0.6))",
          "contrast-high":
            "var(--p-color-contrast-high, hsl(240 7.1% 11% / 0.7))",
        };
        return map[self.props.color || "contrast-lower"];
      },
      get isVertical() {
        return self.props.direction === "vertical";
      },
    };
    if (!this.props) {
      this.props = {};
    }

    this.componentProps = ["color", "direction"];

    // used to keep track of all nodes created by show/for
    this.nodesToDestroy = [];
    // batch updates
    this.pendingUpdate = false;

    if (true) {
      this.attachShadow({ mode: "open" });
    }
  }

  destroyAnyNodes() {
    // destroy current view template refs before rendering again
    this.nodesToDestroy.forEach((el) => el.remove());
    this.nodesToDestroy = [];
  }

  connectedCallback() {
    this.getAttributeNames().forEach((attr) => {
      const jsVar = attr.replace(/-/g, "");
      const regexp = new RegExp(jsVar, "i");
      this.componentProps.forEach((prop) => {
        if (regexp.test(prop)) {
          const attrValue = this.getAttribute(attr);
          if (this.props[prop] !== attrValue) {
            this.props[prop] = attrValue;
          }
        }
      });
    });

    this._root.innerHTML = `
      <hr data-el="hr-probe-divider-1" />
      <style>
        :host {
          display: block;
        }
        :host([hidden]) {
          display: none !important;
        }
        hr {
          all: unset;
          display: block;
        }
        @media (forced-colors: active) {
          hr {
            background: CanvasText;
          }
        }
      </style>`;
    this.pendingUpdate = true;

    this.render();
    this.onMount();
    this.pendingUpdate = false;
    this.update();
  }

  onMount() {}

  onUpdate() {}

  update() {
    if (this.pendingUpdate === true) {
      return;
    }
    this.pendingUpdate = true;
    this.render();
    this.onUpdate();
    this.pendingUpdate = false;
  }

  render() {
    // re-rendering needs to ensure that all nodes generated by for/show are refreshed
    this.destroyAnyNodes();
    this.updateBindings();
  }

  updateBindings() {
    this._root
      .querySelectorAll("[data-el='hr-probe-divider-1']")
      .forEach((el) => {
        Object.assign(el.style, {
          background: this.state.background,
          height: this.state.isVertical ? "100%" : "1px",
          width: this.state.isVertical ? "1px" : "100%",
        });
      });
  }

  // Helper to render content
  renderTextNode(el, text) {
    const textNode = document.createTextNode(text);
    if (el?.scope) {
      textNode.scope = el.scope;
    }
    if (el?.context) {
      textNode.context = el.context;
    }
    el.after(textNode);
    this.nodesToDestroy.push(el.nextSibling);
  }
}

customElements.define("probe-divider", ProbeDivider);
